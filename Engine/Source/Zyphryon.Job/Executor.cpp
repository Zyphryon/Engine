namespace ZyJob
{
    // -=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-
    // -=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-

    void Executor::Stop()
    {
        for (Ref<Thread> Worker : mThreads)
        {
            Worker.request_stop();
        }

        mGate.notify_all();

        for (Ref<Thread> Worker : mThreads)
        {
            Worker.join();
        }
        mThreads.Clear();
    }
}