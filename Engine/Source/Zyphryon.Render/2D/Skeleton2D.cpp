namespace ZyRender
{
    // -=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-
    // -=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-=-

    void Skeleton2D::SetBones(AnyRef<Sequence<Bone>> Bones)
    {
        mBones = Move(Bones);

        mRegistry.Clear();
        mRegistry.Reserve(mBones.GetSize());

        for (UInt Index = 0; Index < mBones.GetSize(); ++Index)
        {
            mRegistry.Assign(mBones[Index].Name, static_cast<UInt16>(Index));
        }
    }
}